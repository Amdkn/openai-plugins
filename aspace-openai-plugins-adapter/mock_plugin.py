#!/usr/bin/env python3
"""aspace-openai-plugins-adapter — mock plugin manifest + structure validator.

Clean-room (D12, D-N048): written from the PUBLIC plugin-manifest format
only (manifest fields as documented in the upstream README: a plugin lives
under plugins/<name>/ with a required `.codex-plugin/plugin.json` manifest).
No upstream file was read, copied, or embedded here. Standard library only.
No network call, no credential, no plugin MCP server is ever started.

Usage:
  mock_plugin.py manifest            -> print a minimal valid manifest (JSON)
  mock_plugin.py validate <dir>      -> structure check (exit 0 ok / 2 bad)
  mock_plugin.py env                 -> telemetry-off environment (JSON)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ADAPTER_VERSION = "0.1.0"
PINNED_OPENAI_PLUGINS_COMMIT = "d420d13051bffe4543ed39e30fa46b87148e47dd"

# Required top-level fields of a plugin manifest, per the public format.
REQUIRED_FIELDS = ("name", "version")
# Optional but expected fields, per the public format.
EXPECTED_FIELDS = ("description", "interface", "skills", "apps", "author")


def minimal_manifest(name: str = "aspace-example") -> dict:
    """Build a minimal valid plugin manifest (own wording, own values)."""
    return {
        "name": name,
        "version": "0.1.0",
        "description": "A minimal example plugin manifest, generated by the "
        "A'Space adapter for contract validation only.",
        "interface": {
            "displayName": "A'Space Example",
            "category": "Productivity",
            "shortDescription": "Contract validation example",
        },
        "skills": "./skills",
        "apps": "./.app.json",
        "author": {"name": "A'Space (adapter-generated example)"},
    }


def validate_plugin_dir(path: Path) -> list[str]:
    """Check the structure of a plugin directory. Returns a list of errors."""
    errors: list[str] = []
    manifest_path = path / ".codex-plugin" / "plugin.json"
    if not manifest_path.is_file():
        return [f"missing manifest: {manifest_path}"]
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError) as exc:
        return [f"manifest is not valid JSON: {exc}"]
    if not isinstance(manifest, dict):
        return ["manifest root is not a JSON object"]
    for field in REQUIRED_FIELDS:
        value = manifest.get(field)
        if not isinstance(value, str) or not value:
            errors.append(f"required field {field!r} missing or not a non-empty string")
    for field in EXPECTED_FIELDS:
        if field not in manifest:
            errors.append(f"expected field {field!r} absent (warning-level, not fatal)")
    # The manifest name should match the directory name (public convention).
    name = manifest.get("name")
    if isinstance(name, str) and name and name != path.name:
        errors.append(f"manifest name {name!r} does not match directory {path.name!r}")
    return errors


def telemetry_off_env() -> dict:
    """Environment proving the adapter is offline by construction."""
    return {
        "DO_NOT_TRACK": "1",
        "ASPACE_ADAPTER_OFFLINE": "1",
        "ASPACE_ADAPTER_NETWORK": "none (stdlib only, no socket/urllib/http)",
        "ASPACE_ADAPTER_CREDENTIALS": "none held, none read",
    }


def main(argv: list[str]) -> int:
    if not argv or argv[0] == "manifest":
        print(json.dumps(minimal_manifest(), indent=2, ensure_ascii=False))
        return 0
    if argv[0] == "validate":
        if len(argv) < 2:
            print("usage: mock_plugin.py validate <plugin-dir>", file=sys.stderr)
            return 2
        errors = validate_plugin_dir(Path(argv[1]))
        if errors:
            for error in errors:
                print(f"INVALID: {error}", file=sys.stderr)
            return 2
        print("VALID")
        return 0
    if argv[0] == "env":
        print(json.dumps(telemetry_off_env(), indent=2, ensure_ascii=False))
        return 0
    print("usage: mock_plugin.py [manifest|validate <dir>|env]", file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
